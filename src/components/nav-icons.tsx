// Icones da barra de navegacao: monocromaticos (currentColor) e todos centrados
// numa caixa 16x16, entao alinham perfeito e herdam a cor do link (ativo/hover).

function make(rows: string[]) {
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const ox = Math.floor((16 - w) / 2);
  const oy = Math.floor((16 - h) / 2);
  const rects: React.ReactNode[] = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      if (r[x] === "#") rects.push(<rect key={`${x}-${y}`} x={x + ox} y={y + oy} width={1} height={1} />);
    }
  });
  return function Icon({ size = 22 }: { size?: number }) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 16 16"
        fill="currentColor"
        shapeRendering="crispEdges"
        style={{ imageRendering: "pixelated" }}
        aria-hidden="true"
      >
        {rects}
      </svg>
    );
  };
}

